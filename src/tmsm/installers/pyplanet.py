def create_pool(name: str, target_server: str, super_pw: str, xmlrpc_port: int, log: Log) -> Path:
    if not is_installed():
        raise RuntimeError("PyPlanet is not installed yet — install it first.")
    cfg = config.load()
    root = paths.PYPLANET_POOLS / name
    if root.exists():
        raise FileExistsError(f"Pool '{name}' already exists at {root}")

    (root / "settings").mkdir(parents=True, exist_ok=True)
    (root / "logs").mkdir(exist_ok=True)
    (root / "tmp").mkdir(exist_ok=True)

    db_name = f"pyplanet_{name.replace('-', '_')}"
    db_user = f"pp_{name.replace('-', '_')}"[:32]
    db_password = ""

    # If MariaDB is installed, provision the DB + user and capture the password.
    from . import mariadb as mariadb_installer
    if mariadb_installer.is_installed():
        log("Provisioning database in MariaDB...")
        db_password = mariadb_installer.provision_database(db_name, db_user, log)
    else:
        log("NOTE: MariaDB is not installed yet. Pool settings will have an empty DB password.")
        log("      Install MariaDB and then re-create the pool, or edit settings/base.py manually.")

    (root / "settings" / "__init__.py").write_text(_SETTINGS_INIT)
    (root / "settings" / "base.py").write_text(_SETTINGS_BASE_TEMPLATE.format(
        pool_name=name,
        xmlrpc_port=xmlrpc_port,
        super_pw=super_pw,
        db_name=db_name,
        db_host=cfg.mariadb.host,
        db_port=cfg.mariadb.port,
        db_user=db_user,
        db_password=db_password,
    ))
    (root / "settings" / "apps.py").write_text(_SETTINGS_APPS_TEMPLATE.format(
        pool_name=name,
    ))
    log(f"Wrote settings for pool '{name}'")

    PoolMeta(
        name=name,
        target_server=target_server,
        db_name=db_name,
        db_user=db_user,
        db_password=db_password,
        settings_module="settings",
    ).save(root)
    log(f"Pool '{name}' created at {root}")
    return root


def delete_pool(name: str, log: Log) -> None:
    root = paths.PYPLANET_POOLS / name
    if not root.exists():
        raise FileNotFoundError(f"Pool '{name}' not found at {root}")
    log(f"Removing {root}")
    shutil.rmtree(root)
    log(f"Pool '{name}' deleted.")
