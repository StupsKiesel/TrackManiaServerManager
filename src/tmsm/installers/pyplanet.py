"""Install the shared PyPlanet and create individual pools."""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from typing import Callable

from .. import config, paths, python38
from ..instances.pool import PoolMeta

Log = Callable[[str], None]


def _run(cmd: list[str], log: Log, cwd: Path | None = None) -> None:
    log(f"$ {' '.join(cmd)}")
    proc = subprocess.Popen(
        cmd,
        cwd=str(cwd) if cwd else None,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )
    assert proc.stdout is not None
    for line in proc.stdout:
        log("  " + line.rstrip())
    rc = proc.wait()
    if rc != 0:
        raise RuntimeError(f"command failed (exit {rc}): {' '.join(cmd)}")


def is_installed() -> bool:
    return (paths.PYPLANET_VENV / "bin" / "pyplanet").is_file()


def install_pyplanet(log: Log) -> None:
    cfg = config.load()
    if is_installed():
        log("PyPlanet already installed.")
        return

    py = python38.ensure_python38(log)
    log(f"Using Python: {py}")

    paths.PYPLANET_DIR.mkdir(parents=True, exist_ok=True)

    if not (paths.PYPLANET_SRC / ".git").exists():
        if paths.PYPLANET_SRC.exists():
            log(f"Removing non-git dir at {paths.PYPLANET_SRC}")
            shutil.rmtree(paths.PYPLANET_SRC)
        _run(["git", "clone", cfg.downloads.pyplanet_git, str(paths.PYPLANET_SRC)], log)
    else:
        log("Updating existing PyPlanet clone")
        _run(["git", "-C", str(paths.PYPLANET_SRC), "fetch", "--tags"], log)

    ref = cfg.downloads.pyplanet_ref
    if ref == "latest-release":
        out = subprocess.run(
            ["git", "-C", str(paths.PYPLANET_SRC), "tag", "--sort=-v:refname"],
            check=True, capture_output=True, text=True,
        )
        tags = [t for t in out.stdout.splitlines() if t.strip()]
        if not tags:
            raise RuntimeError("PyPlanet repo has no tags")
        ref = tags[0]
        log(f"Latest release tag: {ref}")
    _run(["git", "-C", str(paths.PYPLANET_SRC), "checkout", ref], log)

    if not paths.PYPLANET_VENV.exists():
        _run([str(py), "-m", "venv", str(paths.PYPLANET_VENV)], log)
    pip = paths.PYPLANET_VENV / "bin" / "pip"
    _run([str(pip), "install", "--upgrade", "pip", "setuptools", "wheel"], log)
    req = paths.PYPLANET_SRC / "requirements.txt"
    if req.is_file():
        _run([str(pip), "install", "-r", str(req)], log)
    _run([str(pip), "install", "-e", str(paths.PYPLANET_SRC)], log)
    log("PyPlanet installed.")


